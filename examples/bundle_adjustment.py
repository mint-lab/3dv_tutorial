import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import least_squares
from scipy.sparse import lil_matrix
from scipy.spatial.transform import Rotation


# Reprojection error for bundle adjustment
def reprojection_error(params, xs, f, c):
    n_cameras, n_points = xs.shape[:2]
    cameras = params[:n_cameras * 6].reshape(n_cameras, 6)
    Xs = params[n_cameras * 6:].reshape(n_points, 3)

    residuals = []
    for j, camera in enumerate(cameras):
        # X' = R*X + t
        rvec, t = camera[:3], camera[3:]
        R = Rotation.from_rotvec(rvec).as_matrix()
        X = (R @ Xs.T).T + t

        # x' = K*X'
        x_p = f * X[:, :2] / X[:, 2:] + c

        # residual = x - x'
        residuals.append(xs[j] - x_p)
    return np.array(residuals).ravel()


def bundle_adjustment_sparsity(n_cameras, n_points):
    # Each observation depends on one camera (6 parameters) and one point (3 parameters).
    J = lil_matrix((2 * n_cameras * n_points, 6 * n_cameras + 3 * n_points), dtype=int)
    for j in range(n_cameras):
        for i in range(n_points):
            row = 2 * (j * n_points + i)
            J[row:row + 2, 6 * j:6 * j + 6] = 1
            col = 6 * n_cameras + 3 * i
            J[row:row + 2, col:col + 3] = 1
    return J.tocsr()


def main():
    # Note) The following dataset were generated by 'image_formation.py'.
    input = '../data/image_formation%d.xyz'
    input_num = 5
    f, cx, cy = 1000, 320, 240

    # Load 2D points observed from multiple views
    xs = []
    for i in range(input_num):
        pts = np.loadtxt(input % i, ndmin=2)[:, :2]
        assert not xs or len(xs[0]) == len(pts)
        xs.append(pts)
    xs = np.array(xs)

    # Assumption
    # - All cameras have the same and known camera matrix.
    # - All points are visible on all camera views.

    # Initialize cameras and 3D points
    cameras = np.zeros((len(xs), 6))
    Xs = np.tile([0, 0, 5.5], (len(xs[0]), 1))

    # Optimize camera pose and 3D points together (bundle adjustment)
    params = np.concatenate((cameras.ravel(), Xs.ravel()))
    J = bundle_adjustment_sparsity(len(cameras), len(Xs))
    result = least_squares(reprojection_error, params, jac_sparsity=J, x_scale=1.0, verbose=2, args=(xs, f, np.array([cx, cy])))
    cameras = result.x[:len(cameras) * 6].reshape(-1, 6)
    Xs = result.x[len(cameras) * 6:].reshape(-1, 3)

    # Store the 3D points to an XYZ file
    np.savetxt('bundle_adjustment_global(point).xyz', Xs, fmt='%f') # Format: x, y, z

    # Store the camera poses to an XYZ file
    poses = []
    for camera in cameras:
        rvec, t = camera[:3], camera[3:]
        R = Rotation.from_rotvec(rvec).as_matrix()
        p = -R.T @ t
        poses.append(np.concatenate((p, R.T[:, 2])))
    np.savetxt('bundle_adjustment_global(camera).xyz', poses, fmt='%f') # Format: x, y, z, n_x, n_y, n_z

    # Visualize the reconstructed 3D points and camera frustums
    ax = plt.figure(layout='tight').add_subplot(projection='3d')
    ax.plot(Xs[:, 0], Xs[:, 1], Xs[:, 2], 'ro')

    # Draw a small image plane in front of each camera (image size: 640 x 480).
    depth = 0.1 * np.linalg.norm(np.ptp(Xs, axis=0))
    corners = np.array([[-cx, -cy, f], [640 - cx, -cy, f], [640 - cx, 480 - cy, f], [-cx, 480 - cy, f]]) * (depth / f)
    for camera in cameras:
        rvec, t = camera[:3], camera[3:]
        R = Rotation.from_rotvec(rvec).as_matrix()
        p = -R.T @ t
        frame = (R.T @ corners.T).T + p
        border = frame[[0, 1, 2, 3, 0]]
        ax.plot(border[:, 0], border[:, 1], border[:, 2], 'b-')
        for corner in frame:
            ax.plot([p[0], corner[0]], [p[1], corner[1]], [p[2], corner[2]], 'b-')

    ax.set_aspect('equal')
    ax.set_xlabel('X')
    ax.set_ylabel('Y')
    ax.set_zlabel('Z')
    ax.grid(True)
    plt.show()


if __name__ == '__main__':
    main()
